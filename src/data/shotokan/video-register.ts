// ─── Lookups ────────────────────────────────────────────────────────────────

/** Map rather than object literal — see src/data/kata.ts for why. */
const BY_ID = new Map<string, RegisteredVideo>(VIDEOS.map((v) => [v.id, v]));
const SOURCE_BY_KEY = new Map<string, VideoSource>(SOURCES.map((s) => [s.key, s]));

export function videoById(id: string | null | undefined): RegisteredVideo | null {
  if (!id) return null;
  return BY_ID.get(id) ?? null;
}

export function sourceByKey(key: string | null | undefined): VideoSource | null {
  if (!key) return null;
  return SOURCE_BY_KEY.get(key) ?? null;
}

/** Every registered recording of one kata, most authoritative source first. */
export function videosForKata(slug: string): RegisteredVideo[] {
  return VIDEOS.filter((v) => v.kata === slug).sort(
    (a, b) =>
      (sourceByKey(a.discoveredVia)?.authorityRank ?? 999) -
      (sourceByKey(b.discoveredVia)?.authorityRank ?? 999)
  );
}

/** Every registered recording tagged with a topic slug. */
export function videosForTopic(topic: string): RegisteredVideo[] {
  return VIDEOS.filter((v) => v.topics.includes(topic));
}

export function videosOfType(kind: ContentType): RegisteredVideo[] {
  return VIDEOS.filter((v) => v.contentType === kind);
}

/**
 * The recordings that may be embedded without a human rights decision, because
 * the organisation that published them is the organisation being cited.
 *
 * Everything else is a review-queue item, not a publication.
 */
export function selfPublishedByOrganisation(): RegisteredVideo[] {
  return VIDEOS.filter((v) => v.channelIsSourceOrganisation);
}

export function awaitingRightsDecision(): RegisteredVideo[] {
  return VIDEOS.filter((v) => !v.channelIsSourceOrganisation);
}

/** Coverage of the canon, for the research matrix in §50. */
export function kataCoverage(): Map<string, RegisteredVideo[]> {
  const m = new Map<string, RegisteredVideo[]>();
  for (const v of VIDEOS) {
    if (!v.kata) continue;
    const list = m.get(v.kata) ?? [];
    list.push(v);
    m.set(v.kata, list);
  }
  return m;
}
