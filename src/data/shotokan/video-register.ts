/**
 * THE VIDEO SOURCE REGISTER
 * =========================
 *
 * Every external recording the technical library knows about, together with the
 * evidence that somebody actually loaded it.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS FILE IS SHAPED THE WAY IT IS
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * An earlier agent on this project published a video link and recorded evidence
 * of a check it had never performed. src/data/kata.ts carries the scar tissue
 * from that in its header, and tests/kata.test.ts turns it into a rule a code
 * review cannot forget. This file inherits the rule and widens it:
 *
 *   A RECORDING IS ENTERED HERE ONLY WITH THE RESULT OF A REAL CHECK ATTACHED.
 *
 * Every entry below was produced by scripts/discover-videos.mjs, which:
 *
 *   1. fetched the source page named in `discoveredVia` and extracted the
 *      YouTube ids the page itself embeds — no search engine guessing, no
 *      "probably this one";
 *   2. asked YouTube's oEmbed endpoint for each id and kept the title, channel
 *      and channel URL IT RETURNED rather than the label on the source page;
 *   3. loaded the watch page and read the duration, the ISO upload date, the
 *      playabilityStatus and the blockedRegions list;
 *   4. ran a negative control — eleven `A` characters — and REFUSED TO WRITE
 *      ANYTHING if that control passed, because a check that cannot fail is not
 *      a check.
 *
 * `CHECK_METHOD` states all of that in the record itself, in enough detail to
 * be repeated or disbelieved by someone who does not trust this file.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * THE TITLE ON THE PAGE IS NOT THE TITLE OF THE VIDEO
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * A collection page captions its embeds by hand, and captions drift: a form is
 * relabelled, a video is swapped, a typo outlives everyone who noticed it. So
 * the title and channel here are the platform's, not the page's. Where the two
 * disagree, the platform wins, and the disagreement is a fact about the source
 * worth knowing.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * AND THE FIELD THAT DECIDES WHAT MAY BE SHOWN
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * `channelIsSourceOrganisation` is the most consequential thing in this file,
 * and the reason the library does not simply publish all 121 recordings.
 *
 * Two very different things were found at the sources the directive names:
 *
 *   · Videos an organisation uploaded to ITS OWN channel and embedded on ITS
 *     OWN site. JKA India's camp, kihon and kumite footage on @JKAIndiahq;
 *     Cambridge University Karate Club's footage on @cukarate. The organisation
 *     published it, left embedding switched on, and is the party with standing
 *     to say so. Referencing that is uncontroversial.
 *
 *   · Videos a THIRD PARTY uploaded, which an organisation then embedded. The
 *     twenty-six kata collection on skif.co.nz plays from a channel called
 *     `shotokankataman`; Colchester JKA's kata page plays Enoeda and Ohta
 *     Sensei's JKA demonstrations from channels called `iZafod` and
 *     `1000MOSHT`. These are the most technically valuable recordings in the
 *     whole haul — and nobody in this repository knows whether the uploader had
 *     the right to upload them. SKIF NZ's editorial judgement is SKIF NZ's; it
 *     is not a rights clearance, and it is certainly not MMAKF's.
 *
 * So the flag records the fact, and src/db/shotokan.ts turns it into policy:
 * `false` means the recording enters the review queue needing a rights decision
 * and is NOT published until a human makes one. The federation republishing a
 * re-upload of another organisation's material under its own banner is exactly
 * what §49 of the directive forbids by name.
 *
 * NOTHING HERE IS MMAKF CURRICULUM. These are references. MMAKF's own footage
 * lives in src/data/kata.ts under FEDERATION_KATA_FOOTAGE and is the only
 * material this platform describes as the federation's own.
 */

// ─── Types ──────────────────────────────────────────────────────────────────

/**
 * A place the library looks for material, and what MMAKF may say about it.
 *
 * `authorityRank` is a DEFAULT, not a doctrine. §41 of the directive is
 * explicit that a permanent organisational hierarchy must not be encoded in
 * code, so this number seeds `video_sources.authority_rank` at install time and
 * an administrator changes it thereafter. The database is authoritative; this
 * file only records where the first value came from.
 */
export interface VideoSource {
  key: string;
  /** The organisation, named as it names itself. */
  organisation: string;
  /** The exact page that was fetched. */
  url: string;
  kind:
    | 'institutional_shotokan'
    | 'national_organisation'
    | 'university_club'
    | 'federation_own';
  /** Lower is more authoritative. Seeds the database; not permanent. */
  authorityRank: number;
  /** What this source actually is, in plain words. */
  note: string;
  /** ISO date the page was last fetched by the discovery pass. */
  fetchedOn: string;
  /** Videos the page embedded, before any verification. */
  candidatesFound: number;
  /** Of those, how many resolved to a live, embeddable recording. */
  candidatesVerified: number;
}

export type ContentType =
  | 'kata_demonstration'
  | 'kihon_reference'
  | 'kumite_reference'
  | 'teaching_breakdown'
  | 'competition_performance'
  | 'seminar'
  | 'technical_demonstration';

/** A recording, with the evidence of its check. */
export interface RegisteredVideo {
  /** The YouTube id. Also the natural key — a video is registered once. */
  id: string;
  /** As YouTube reported it, not as the source page captioned it. */
  title: string;
  channel: string;
  channelUrl: string;
  thumbnailUrl: string;
  /** Read off the watch page. Null would mean it was not readable. */
  durationSeconds: number | null;
  /** ISO. Read off the watch page, never a localised human string. */
  publishedOn: string | null;
  /** Which source page embedded it. Keys into SOURCES. */
  discoveredVia: string;
  contentType: ContentType;
  /** Kata slug, matched from the platform title. Null where it is not a kata. */
  kata: string | null;
  /** Conservative topic tags. A wrong tag is worse than no tag. */
  topics: readonly string[];
  /** See the header. This is what decides whether it may be published. */
  channelIsSourceOrganisation: boolean;
}

